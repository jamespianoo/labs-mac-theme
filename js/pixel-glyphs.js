  /* Set text in a face. Returns rows of '0'/'1' plus size. */
  function setText(face, text) {
    var chars = String(text).toUpperCase().split('');
    var rows = [], r, i, g, width = 0, pieces = [];
    for (i = 0; i < chars.length; i++) {
      if (chars[i] === ' ') { pieces.push({ space: face.space }); continue; }
      g = face.glyphs[chars[i]];
      if (g) pieces.push({ g: g });
    }
    for (r = 0; r < face.height; r++) rows.push('');
    for (i = 0; i < pieces.length; i++) {
      var p = pieces[i];
      var add = p.g ? p.g[0].length : p.space;
      var gap = i > 0 && p.g && pieces[i - 1].g ? face.gap : 0;
      for (r = 0; r < face.height; r++) {
        rows[r] += repeat('0', gap) + (p.g ? p.g[r] : repeat('0', add));
      }
      width += gap + add;
    }
    return { rows: rows, width: width, height: face.height };
  }

  function repeat(ch, n) {
    var s = '';
    while (n-- > 0) s += ch;
    return s;
  }

  /* Stack lines of bitmap, centred, with a gap of blank rows between. */
  function stack(lines, gapRows) {
    var width = 0, i, r;
    for (i = 0; i < lines.length; i++) width = Math.max(width, lines[i].width);
    var rows = [];
    for (i = 0; i < lines.length; i++) {
      if (i > 0) for (r = 0; r < gapRows; r++) rows.push(repeat('0', width));
      var pad = Math.floor((width - lines[i].width) / 2);
      for (r = 0; r < lines[i].height; r++) {
        rows.push(repeat('0', pad) + lines[i].rows[r] + repeat('0', width - pad - lines[i].width));
      }
    }
    return { rows: rows, width: width, height: rows.length };
  }

